import { jsPDF } from 'jspdf';
import 'svg2pdf.js';
import { AGE_GROUPS, ALL_AGES, ESTIMATE, fmtInt, fmtPct, fmtPts, yearLabel } from './metrics.js';
import { colorScale, drawMap } from './map.js';

const INK = [22, 22, 20], INK2 = [82, 81, 78], INK3 = [117, 116, 111], RULE = [226, 225, 220], ACCENT = [11, 138, 116];

/** Build and download a 2-page letter-size PDF report for the current selection. */
export async function exportReport({ model, geo, meta, year, group, save = true }) {
  const doc = new jsPDF({ unit: 'pt', format: 'letter' });
  const PW = doc.internal.pageSize.getWidth(), M = 48;
  let y = M;

  const text = (s, x, yy, { size = 10, color = INK, bold = false, maxWidth } = {}) => {
    s = pdfSafe(s);
    doc.setFont('helvetica', bold ? 'bold' : 'normal').setFontSize(size).setTextColor(...color);
    const lines = maxWidth ? doc.splitTextToSize(s, maxWidth) : [s];
    doc.text(lines, x, yy);
    return lines.length * size * 1.25;
  };
  const rule = (yy) => { doc.setDrawColor(...RULE).setLineWidth(0.75).line(M, yy, PW - M, yy); };

  // ---- Page 1: title, sources, statewide summary, map ----
  doc.setFillColor(...ACCENT).rect(0, 0, PW, 6, 'F');
  y += text('Georgia County Turnout Analyzer', M, y + 8, { size: 20, bold: true }) + 2;
  y += text(`Report generated ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })} · View: ${group}, ${yearLabel(year)}`, M, y + 4, { size: 10, color: INK2 });
  if (meta.is_sample) {
    doc.setFillColor(255, 243, 214).roundedRect(M, y + 6, PW - 2 * M, 22, 4, 4, 'F');
    text('SAMPLE DATA — numbers in this report are fake placeholders, not real election results.', M + 10, y + 21, { size: 9.5, bold: true, color: [92, 61, 0] });
    y += 30;
  }
  y += 10;
  const sources = meta.is_sample
    ? 'Sample data generated by scripts/clean_data.py (no real files present).'
    : 'Georgia Secretary of State: Voter Turnout by Demographics report (Nov 6, 2018 general election); Election Data Hub, Turnout & Demographics (Nov 8, 2022 general election). County boundaries: U.S. Census Bureau cartographic boundary files.';
  y += text('Data sources', M, y + 8, { size: 10, bold: true });
  y += text(sources, M, y + 8, { size: 9, color: INK2, maxWidth: PW - 2 * M }) + 6;
  rule(y); y += 16;

  // Statewide summary table
  y += text('Statewide summary — turnout rate by age group', M, y + 4, { size: 12, bold: true }) + 4;
  const cols = [
    { h: 'Age group', w: 90, a: 'left' },
    { h: `${model.firstYear}`, w: 70 }, { h: `${model.lastYear}`, w: 70 },
    { h: 'Change', w: 80 }, { h: '2026 est.*', w: 80 }, { h: `Registered ${model.lastYear}`, w: 116 },
  ];
  const drawRow = (cells, yy, { bold = false, color = INK } = {}) => {
    let x = M;
    cells.forEach((c, i) => {
      const col = cols[i];
      const tx = col.a === 'left' ? x + 4 : x + col.w - 4;
      doc.setFont('helvetica', bold ? 'bold' : 'normal').setFontSize(9.5).setTextColor(...color);
      doc.text(pdfSafe(c), tx, yy, { align: col.a === 'left' ? 'left' : 'right' });
      x += col.w;
    });
  };
  doc.setFillColor(240, 239, 236).rect(M, y, PW - 2 * M, 18, 'F');
  drawRow(cols.map((c) => c.h), y + 12.5, { bold: true });
  y += 18;
  for (const g of [...AGE_GROUPS, ALL_AGES]) {
    drawRow([g, fmtPct(model.stateRate(model.firstYear, g)), fmtPct(model.stateRate(model.lastYear, g)),
      fmtPts(model.stateChange(g)), fmtPct(model.stateRate(ESTIMATE, g)), fmtInt(model.stateRegistered(model.lastYear, g))],
      y + 13, { bold: g === ALL_AGES });
    y += 17;
    doc.setDrawColor(...RULE).setLineWidth(0.5).line(M, y, PW - M, y);
  }
  y += 6;
  y += text('* 2026 estimate = simple average of the 2018 and 2022 rates. It is not a prediction model.', M, y + 8, { size: 8, color: INK3 }) + 10;

  // Map
  y += text(`Turnout rate by county — ${group}, ${yearLabel(year)}`, M, y + 4, { size: 12, bold: true }) + 6;
  const values = model.counties.map((c) => model.rate(c, year, group));
  const scale = colorScale(values, 'light');
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('width', '600'); svg.setAttribute('height', '680');
  svg.style.position = 'absolute'; svg.style.left = '-9999px';
  document.body.appendChild(svg);
  drawMap(svg, geo, { value: (c) => model.rate(c, year, group), color: scale, stroke: '#ffffff' });
  const mapH = 792 - M - y - 34, mapW = mapH * (600 / 680);
  await doc.svg(svg, { x: M, y, width: mapW, height: mapH });
  svg.remove();

  // Legend beside the map
  const lx = M + mapW + 24, ly = y + 20;
  text('Turnout rate', lx, ly, { size: 9, bold: true });
  const [d0, d1] = scale.domain();
  const steps = 6;
  for (let i = 0; i < steps; i++) {
    const v = d1 - ((d1 - d0) * i) / (steps - 1);
    const c = scale(v).match(/\d+/g).map(Number);
    doc.setFillColor(...c).rect(lx, ly + 10 + i * 18, 14, 14, 'F');
    text(fmtPct(v, 0), lx + 20, ly + 21 + i * 18, { size: 9, color: INK2 });
  }
  const best = model.counties.map((c) => ({ c, r: model.rate(c, year, group) })).filter((d) => d.r != null).sort((a, b) => b.r - a.r);
  let ny = ly + 10 + steps * 18 + 20;
  ny += text('Highest', lx, ny, { size: 9, bold: true });
  best.slice(0, 3).forEach((d) => { ny += text(`${d.c} ${fmtPct(d.r)}`, lx, ny, { size: 9, color: INK2 }); });
  ny += 8;
  ny += text('Lowest', lx, ny, { size: 9, bold: true });
  best.slice(-3).reverse().forEach((d) => { ny += text(`${d.c} ${fmtPct(d.r)}`, lx, ny, { size: 9, color: INK2 }); });

  footer(doc, 1, meta);

  // ---- Page 2: top-15 opportunities + methodology ----
  doc.addPage();
  doc.setFillColor(...ACCENT).rect(0, 0, PW, 6, 'F');
  y = M;
  const oppYear = year;
  y += text(`Biggest opportunities — ${group === ALL_AGES ? 'all age groups' : `age ${group}`}, ${yearLabel(oppYear)}`, M, y + 8, { size: 14, bold: true }) + 2;
  y += text('County and age-group pairs with turnout below the statewide rate for that group, ranked by registered voters who did not vote: registered × (1 − turnout rate).', M, y + 6, { size: 9, color: INK2, maxWidth: PW - 2 * M }) + 8;

  const ocols = [
    { h: '#', w: 26, a: 'left' }, { h: 'County', w: 130, a: 'left' }, { h: 'Age', w: 60, a: 'left' },
    { h: 'Turnout', w: 64 }, { h: 'Statewide', w: 70 }, { h: 'Registered', w: 82 }, { h: 'Did not vote', w: 84 },
  ];
  const drawORow = (cells, yy, bold) => {
    let x = M;
    cells.forEach((c, i) => {
      const col = ocols[i];
      doc.setFont('helvetica', bold ? 'bold' : 'normal').setFontSize(9.5).setTextColor(...INK);
      doc.text(pdfSafe(c), col.a === 'left' ? x + 4 : x + col.w - 4, yy, { align: col.a === 'left' ? 'left' : 'right' });
      x += col.w;
    });
  };
  doc.setFillColor(240, 239, 236).rect(M, y, PW - 2 * M, 18, 'F');
  drawORow(ocols.map((c) => c.h), y + 12.5, true);
  y += 18;
  model.opportunities(oppYear, group).forEach((o, i) => {
    drawORow([i + 1, o.county, o.group, fmtPct(o.rate), fmtPct(o.stateRate), fmtInt(o.registered), fmtInt(o.nonVoters)], y + 13);
    y += 17;
    doc.setDrawColor(...RULE).setLineWidth(0.5).line(M, y, PW - M, y);
  });
  y += 24;

  y += text('Methodology', M, y, { size: 12, bold: true }) + 2;
  const method = [
    'Turnout rate = ballots cast ÷ registered voters (active + inactive), per county, age group, and election.',
    "Age groups combine the Secretary of State's 5-year brackets (e.g., 25-29 + 30-34 = 25-34; all ages 65 and older = 65+). Age is based on birth year in the voter file.",
    `Change = ${model.lastYear} rate − ${model.firstYear} rate. Gap = county rate − statewide rate for the same age group and election. Both in percentage points.`,
    '2026 estimate = simple average of the 2018 and 2022 rates. It is shown for context only and is not a prediction model: it ignores new registrations, candidates, mobilization, and other factors.',
    meta.is_sample ? 'This report uses SAMPLE (fake) data.' : '2022 counts use the SoS Data Hub voter base as of the Oct 11, 2022 registration deadline; 6,115 ballots (0.15%) without a matching age record are excluded from age-group figures. Statewide ballot totals match certified results within 0.25% for both elections.',
    'Nonpartisan: this analysis uses only aggregate, public data and no individual voter records. It does not consider party or vote choice.',
  ];
  for (const m of method) {
    doc.setFillColor(...INK3).circle(M + 3, y + 3.5, 1.4, 'F');
    y += text(m, M + 12, y + 7, { size: 9.5, color: INK2, maxWidth: PW - 2 * M - 12 }) + 4;
  }

  footer(doc, 2, meta);
  if (save) doc.save(`ga-turnout-report-${group.replace(/\W+/g, '')}-${year}.pdf`);
  return doc;
}

// The built-in PDF fonts only cover WinAnsi; swap characters outside it.
function pdfSafe(v) {
  return String(v).replace(/\u2212/g, '-').replace(/\u2192/g, ' to ').replace(/\u2248/g, '~');
}

function footer(doc, page, meta) {
  const PW = doc.internal.pageSize.getWidth(), PH = doc.internal.pageSize.getHeight();
  doc.setFont('helvetica', 'normal').setFontSize(7.5).setTextColor(...INK3);
  doc.text(`Georgia County Turnout Analyzer · Nonpartisan · Aggregate public data only · Data updated ${meta.generated}`, 48, PH - 24);
  doc.text(`Page ${page} of 2`, PW - 48, PH - 24, { align: 'right' });
}
